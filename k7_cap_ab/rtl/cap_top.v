// 10G packet capture on both SFP+ cages (k7_cap_ab): per-port receive path -> on-chip
// buffers -> record merge -> one PCIe DMA ring.
//
// Clock domains: rx_clk_a / rx_clk_b (each cage's RX PCS clock: MAC receiver, test
// generator, ingress), ts_clk (156.25 MHz TX PCS clock from the local SFP refclk: one
// timestamp counter for both ports), clk (PCIe user clock 250 MHz: registers, merge, DMA).
// Crossings: data/meta FIFOs (afifo), Gray-coded timestamp, 2-flop synchronisers for
// quasi-static configuration (change SNAPLEN / TG_CFG / keep bits only while CTRL.enable
// is 0), toggle-qualified counter snapshots.
//
// Registers (byte offsets in BAR0; this block decodes 0x100..0x1FF). As k7_cap, plus
// PORTS, the B status bit and the port B counters:
//   0x100 CTRL       RW [0] enable  [1] reset (held while 1: FIFOs, ring head, counters)
//                       [2] keep bad frames (FCS / framing errors) [3] keep FCS bytes
//                       [4] test generators replace the MAC inputs (of the enabled ports)
//   0x104 STATUS     RO [0] bus master enabled [1] DMA running [4:2] Device Control MPS
//                       [5] SFP A block lock [6] SFP B block lock [25:16] prefetch FIFO level
//   0x108 SNAPLEN    RW bytes kept per frame, multiple of 8, 64..16384 (reset 9600)
//   0x10C BLKCFG     RW [4:0] log2 block size (12..30, reset 21 = 2 MB) [26:16] blocks (1..1024)
//   0x110 TBL_IDX    RW [9:0] block table index (auto-increments on TBL_HI writes)
//   0x114 TBL_LO     RW bus address bits 31:0 (held until TBL_HI is written)
//   0x118 TBL_HI     WO bus address bits 63:32; writes table[TBL_IDX] = {HI, LO}
//   0x11C TIMEOUT    RW [15:0] flush / status timeout in 4 ns units (reset 250 = 1 us)
//   0x120 STAT_LO    RW status writeback bus address (8 bytes: head)
//   0x124 STAT_HI    RW
//   0x128 STAT_THR   RW bytes of new data between status writes (reset 65536)
//   0x12C TAIL       RW low 32 bits of the bytes the host has consumed
//   0x130 HEAD       RO 64-bit bytes written to the ring (lo, then hi)
//   0x138 TS         RO 64-bit timestamp counter now (6.4 ns ticks)
//   0x140 TG_CFG     RW test generators [15:0] frame bytes (reset 60) [31:16] gap cycles (reset 3)
//   0x144 FIFO_MAX   RO highest data FIFO level since reset, [15:0] port A [31:16] port B
//                       (words of 8 bytes; each FIFO holds 32768)
//   0x148 PORTS      RW [0] capture SFP A [1] capture SFP B (reset 1: A only, as k7_cap)
//   0x150 RX_FRAMES  RO port A: frames from the MAC (or generator), all     \
//   0x158 RX_BYTES   RO port A: bytes of those                               |
//   0x160 CAP_FRAMES RO port A: frames accepted into the buffers             | 64-bit:
//   0x168 DROP_FRAMES RO port A: frames dropped, buffers full (while enabled)| read lo
//   0x170 BAD_FRAMES RO port A: FCS / framing errors                         | (latches
//   0x178 RECORDS    RO records handed to the DMA writer (both ports)       | hi), then
//   0x180 TLPS       RO memory write TLPs sent                               | hi.
//   0x188 STALLS     RO writer decisions blocked by a full host ring          | Port
//   0x190 TG_SEQ     RO port A: frames generated by its test generator       | counters
//   0x1A0 RX_FRAMES_B, 0x1A8 RX_BYTES_B, 0x1B0 CAP_FRAMES_B, 0x1B8 DROP_FRAMES_B,| update
//   0x1C0 BAD_FRAMES_B, 0x1C8 TG_SEQ_B: the same for port B                 / every 105 us
`default_nettype none
module cap_top (
  input  wire         clk,          // PCIe user clock
  input  wire         rst,          // por | user_reset
  input  wire         rx_clk_a,
  input  wire         rx_rst_a,     // SFP A RX PCS reset
  input  wire [63:0]  xgmii_rxd_a,
  input  wire [7:0]   xgmii_rxc_a,
  input  wire         rx_clk_b,
  input  wire         rx_rst_b,     // SFP B RX PCS reset
  input  wire [63:0]  xgmii_rxd_b,
  input  wire [7:0]   xgmii_rxc_b,
  input  wire         ts_clk,
  input  wire         sfp_a_lock,   // async
  input  wire         sfp_b_lock,   // async

  // register bus (clk): req strobe, read data the cycle after
  input  wire         req,
  input  wire         we,
  input  wire [11:2]  addr,
  input  wire [31:0]  wdata,
  output reg  [31:0]  rdata,

  input  wire [15:0]  requester_id,
  input  wire         bus_master_en,
  input  wire [2:0]   cfg_mps,

  output wire [63:0]  tx_tdata,
  output wire [7:0]   tx_tkeep,
  output wire         tx_tlast,
  output wire         tx_tvalid,
  input  wire         tx_tready
);
  localparam integer DAW = 15, MAW = 12;

  // ---------------- registers ----------------
  reg        r_enable = 1'b0, r_reset = 1'b0, r_keep_bad = 1'b0, r_keep_fcs = 1'b0, r_tg = 1'b0;
  reg [1:0]  r_ports = 2'b01;
  reg [14:0] r_snap = 15'd9600;
  reg [4:0]  r_blk_shift = 5'd21;
  reg [10:0] r_nblocks = 11'd1;
  reg [9:0]  r_tbl_idx = 0;
  reg [31:0] r_tbl_lo = 0;
  reg [15:0] r_timeout = 16'd250;
  reg [63:0] r_stat_addr = 0;
  reg [31:0] r_stat_thr = 32'd65536;
  reg [31:0] r_tail = 0;
  reg [31:0] r_tg_cfg = {16'd3, 16'd60};
  reg        tbl_we = 1'b0;
  reg [63:0] tbl_wdata = 0;
  reg [9:0]  tbl_waddr = 0;
  reg [31:0] hi_hold = 0;

  // capture reset, registered (drives asynchronous resets)
  reg cap_rst = 1'b1;
  always @(posedge clk) cap_rst <= rst | r_reset;

  // per-port enables, registered before they cross into the RX clock domains
  reg en_a = 1'b0, en_b = 1'b0;
  always @(posedge clk) begin
    en_a <= r_enable & bus_master_en & r_ports[0];
    en_b <= r_enable & bus_master_en & r_ports[1];
  end

  // ---------------- timestamp: ts_clk counter, Gray to clk (each port syncs its own) ----------------
  reg [63:0] ts_bin = 0, ts_gray = 0;
  always @(posedge ts_clk) begin
    ts_bin  <= ts_bin + 1'b1;
    ts_gray <= ts_bin ^ (ts_bin >> 1);
  end
  function [63:0] g2b(input [63:0] g);
    integer k;
    for (k = 0; k < 64; k = k + 1) g2b[k] = ^(g >> k);
  endfunction
  (* ASYNC_REG = "TRUE" *) reg [63:0] tsu_s1 = 0, tsu_s2 = 0;
  reg [63:0] ts_u = 0;
  always @(posedge clk) begin tsu_s1 <= ts_gray; tsu_s2 <= tsu_s1; ts_u <= g2b(tsu_s2); end

  // ---------------- the two capture inputs ----------------
  wire [127:0] ma_data, mb_data;  wire ma_valid, mb_valid, ma_pop, mb_pop;
  wire [63:0]  da_data, db_data;  wire da_valid, db_valid, da_pop, db_pop;
  wire [63:0]  a_rxf, a_rxb, a_cap, a_drop, a_bad, a_tg;
  wire [63:0]  b_rxf, b_rxb, b_cap, b_drop, b_bad, b_tg;
  wire [DAW:0] a_dmax, b_dmax;

  cap_port #(.DAW(DAW), .MAW(MAW), .PORT(7'd0)) port_a (
    .clk(clk), .cap_rst(cap_rst),
    .rx_clk(rx_clk_a), .rx_rst(rx_rst_a), .xgmii_rxd(xgmii_rxd_a), .xgmii_rxc(xgmii_rxc_a),
    .ts_gray(ts_gray),
    .cfg_enable(en_a), .cfg_keep_bad(r_keep_bad), .cfg_keep_fcs(r_keep_fcs), .cfg_tg(r_tg),
    .cfg_snap_words(r_snap[14:3]), .cfg_tg_cfg(r_tg_cfg),
    .m_rdata(ma_data), .m_rvalid(ma_valid), .m_rpop(ma_pop),
    .d_rdata(da_data), .d_rvalid(da_valid), .d_rpop(da_pop),
    .u_rxf(a_rxf), .u_rxb(a_rxb), .u_cap(a_cap), .u_drop(a_drop), .u_bad(a_bad), .u_tg(a_tg),
    .u_dmax(a_dmax)
  );

  cap_port #(.DAW(DAW), .MAW(MAW), .PORT(7'd1)) port_b (
    .clk(clk), .cap_rst(cap_rst),
    .rx_clk(rx_clk_b), .rx_rst(rx_rst_b), .xgmii_rxd(xgmii_rxd_b), .xgmii_rxc(xgmii_rxc_b),
    .ts_gray(ts_gray),
    .cfg_enable(en_b), .cfg_keep_bad(r_keep_bad), .cfg_keep_fcs(r_keep_fcs), .cfg_tg(r_tg),
    .cfg_snap_words(r_snap[14:3]), .cfg_tg_cfg(r_tg_cfg),
    .m_rdata(mb_data), .m_rvalid(mb_valid), .m_rpop(mb_pop),
    .d_rdata(db_data), .d_rvalid(db_valid), .d_rpop(db_pop),
    .u_rxf(b_rxf), .u_rxb(b_rxb), .u_cap(b_cap), .u_drop(b_drop), .u_bad(b_bad), .u_tg(b_tg),
    .u_dmax(b_dmax)
  );

  // ---------------- merge: whole records, round robin ----------------
  wire [127:0] m_rdata;  wire m_rvalid, m_rpop;
  wire [63:0]  d_rdata;  wire d_rvalid, d_rpop;
  cap_merge merge (
    .clk(clk), .rst(cap_rst),
    .m0_data(ma_data), .m0_valid(ma_valid), .m0_pop(ma_pop),
    .d0_data(da_data), .d0_valid(da_valid), .d0_pop(da_pop),
    .m1_data(mb_data), .m1_valid(mb_valid), .m1_pop(mb_pop),
    .d1_data(db_data), .d1_valid(db_valid), .d1_pop(db_pop),
    .m_data(m_rdata), .m_valid(m_rvalid), .m_pop(m_rpop),
    .d_data(d_rdata), .d_valid(d_rvalid), .d_pop(d_rpop)
  );

  // ---------------- DMA ----------------
  wire [63:0] head, c_tlps, c_stall, c_records;
  wire [9:0]  pf_level;
  // The DMA keeps running after CTRL.enable drops (drains what is buffered) until reset.
  reg         r_armed = 1'b0;
  always @(posedge clk) if (cap_rst) r_armed <= 1'b0; else if (r_enable) r_armed <= 1'b1;
  wire        run = r_armed & bus_master_en;
  cap_dma dma (
    .clk(clk), .rst(cap_rst),
    .m_data(m_rdata), .m_valid(m_rvalid), .m_pop(m_rpop),
    .d_data(d_rdata), .d_valid(d_rvalid), .d_pop(d_rpop),
    .cfg_run(run), .cfg_mps(cfg_mps), .cfg_blk_shift(r_blk_shift), .cfg_nblocks(r_nblocks),
    .cfg_tail(r_tail), .cfg_stat_addr(r_stat_addr), .cfg_stat_thresh(r_stat_thr),
    .cfg_timeout(r_timeout), .requester_id(requester_id),
    .tbl_we(tbl_we), .tbl_waddr(tbl_waddr), .tbl_wdata(tbl_wdata),
    .tx_tdata(tx_tdata), .tx_tkeep(tx_tkeep), .tx_tlast(tx_tlast), .tx_tvalid(tx_tvalid), .tx_tready(tx_tready),
    .head(head), .c_tlps(c_tlps), .c_stall(c_stall), .c_records(c_records), .pf_level(pf_level)
  );

  // ---------------- clk domain: status, register access ----------------
  (* ASYNC_REG = "TRUE" *) reg [1:0] lock_a_s = 0, lock_b_s = 0;
  always @(posedge clk) begin
    lock_a_s <= {lock_a_s[0], sfp_a_lock};
    lock_b_s <= {lock_b_s[0], sfp_b_lock};
  end

  wire wr = req && we && addr[11:8] == 4'h1;
  wire rd = req && !we && addr[11:8] == 4'h1;
  // 64-bit registers: even word offsets 0x130.. except 0x140 TG_CFG, 0x144 FIFO_MAX, 0x148 PORTS
  wire is64 = addr[7:2] >= 6'h0C && addr[7:2] != 6'h10 && addr[7:2] != 6'h11 &&
              addr[7:2] != 6'h12 && !addr[2];
  reg [63:0] sel64;
  always @* begin
    case (addr[7:3])
      5'h06: sel64 = head;
      5'h07: sel64 = ts_u;
      5'h0A: sel64 = a_rxf;
      5'h0B: sel64 = a_rxb;
      5'h0C: sel64 = a_cap;
      5'h0D: sel64 = a_drop;
      5'h0E: sel64 = a_bad;
      5'h0F: sel64 = c_records;
      5'h10: sel64 = c_tlps;
      5'h11: sel64 = c_stall;
      5'h12: sel64 = a_tg;
      5'h14: sel64 = b_rxf;
      5'h15: sel64 = b_rxb;
      5'h16: sel64 = b_cap;
      5'h17: sel64 = b_drop;
      5'h18: sel64 = b_bad;
      5'h19: sel64 = b_tg;
      default: sel64 = 64'd0;
    endcase
  end

  always @(posedge clk) begin
    tbl_we <= 1'b0;
    if (req) begin
      if (is64) begin
        rdata <= sel64[31:0];
        if (rd) hi_hold <= sel64[63:32];
      end else case (addr[7:2])
        6'h00: rdata <= {27'd0, r_tg, r_keep_fcs, r_keep_bad, r_reset, r_enable};
        6'h01: rdata <= {6'd0, pf_level, 9'd0, lock_b_s[1], lock_a_s[1], cfg_mps, run, bus_master_en};
        6'h02: rdata <= {17'd0, r_snap};
        6'h03: rdata <= {5'd0, r_nblocks, 11'd0, r_blk_shift};
        6'h04: rdata <= {22'd0, r_tbl_idx};
        6'h05: rdata <= r_tbl_lo;
        6'h07: rdata <= {16'd0, r_timeout};
        6'h08: rdata <= r_stat_addr[31:0];
        6'h09: rdata <= r_stat_addr[63:32];
        6'h0A: rdata <= r_stat_thr;
        6'h0B: rdata <= r_tail;
        6'h10: rdata <= r_tg_cfg;
        6'h11: rdata <= {b_dmax, a_dmax};
        6'h12: rdata <= {30'd0, r_ports};
        default: rdata <= (addr[7:2] >= 6'h0C) ? hi_hold : 32'd0;
      endcase
    end
    if (wr) case (addr[7:2])
      6'h00: begin
        r_enable <= wdata[0];  r_reset <= wdata[1];  r_keep_bad <= wdata[2];
        r_keep_fcs <= wdata[3];  r_tg <= wdata[4];
      end
      6'h02: r_snap <= (wdata > 32'd16384) ? 15'd16384 :
                       (wdata < 32'd64) ? 15'd64 : {wdata[14:3], 3'b000};
      6'h03: begin
        r_blk_shift <= (wdata[4:0] < 5'd12) ? 5'd12 : (wdata[4:0] > 5'd30 ? 5'd30 : wdata[4:0]);
        r_nblocks   <= (wdata[26:16] == 0) ? 11'd1 : (wdata[26:16] > 11'd1024 ? 11'd1024 : wdata[26:16]);
      end
      6'h04: r_tbl_idx <= wdata[9:0];
      6'h05: r_tbl_lo  <= wdata;
      6'h06: begin
        tbl_we <= 1'b1;  tbl_waddr <= r_tbl_idx;  tbl_wdata <= {wdata, r_tbl_lo};
        r_tbl_idx <= r_tbl_idx + 1'b1;
      end
      6'h07: r_timeout <= (wdata[15:0] == 0) ? 16'd1 : wdata[15:0];
      6'h08: r_stat_addr[31:0]  <= {wdata[31:3], 3'b000};
      6'h09: r_stat_addr[63:32] <= wdata;
      6'h0A: r_stat_thr <= wdata;
      6'h0B: r_tail <= wdata;
      6'h10: r_tg_cfg <= wdata;
      6'h12: r_ports <= wdata[1:0];
      default: ;
    endcase
    if (rst) begin
      r_enable <= 1'b0;  r_reset <= 1'b0;
    end
  end
endmodule
`default_nettype wire
