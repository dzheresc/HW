// 10G packet capture (k7_cap): SFP A receive path -> on-chip buffers -> PCIe DMA ring.
//
// Clock domains: rx_clk (SFP A RX PCS clock: MAC receiver, test generator, ingress),
// ts_clk (156.25 MHz TX PCS clock from the local SFP refclk: timestamp counter),
// clk (PCIe user clock 250 MHz: registers, DMA). Crossings: data/meta FIFOs (afifo),
// Gray-coded timestamp, 2-flop synchronisers for quasi-static configuration (change
// SNAPLEN / TG_CFG only while CTRL.enable is 0), toggle-qualified counter snapshots.
//
// Registers (byte offsets in BAR0; this block decodes 0x100..0x1FF):
//   0x100 CTRL       RW [0] enable  [1] reset (held while 1: FIFOs, ring head, counters)
//                       [2] keep bad frames (FCS / framing errors) [3] keep FCS bytes
//                       [4] test generator replaces the MAC input
//   0x104 STATUS     RO [0] bus master enabled [1] DMA running [4:2] Device Control MPS
//                       [5] SFP A block lock [25:16] prefetch FIFO level (words)
//   0x108 SNAPLEN    RW bytes kept per frame, multiple of 8, 64..16384 (reset 9600)
//   0x10C BLKCFG     RW [4:0] log2 block size (12..30, reset 21 = 2 MB) [26:16] blocks (1..1024)
//   0x110 TBL_IDX    RW [9:0] block table index (auto-increments on TBL_HI writes)
//   0x114 TBL_LO     RW bus address bits 31:0 (held until TBL_HI is written)
//   0x118 TBL_HI     WO bus address bits 63:32; writes table[TBL_IDX] = {HI, LO}
//   0x11C TIMEOUT    RW [15:0] flush / status timeout in 4 ns units (reset 250 = 1 us)
//   0x120 STAT_LO    RW status writeback bus address (8 bytes: head)
//   0x124 STAT_HI    RW
//   0x128 STAT_THR   RW bytes of new data between status writes (reset 65536)
//   0x12C TAIL       RW low 32 bits of the bytes the host has consumed
//   0x130 HEAD       RO 64-bit bytes written to the ring (lo, then hi)
//   0x138 TS         RO 64-bit timestamp counter now (6.4 ns ticks)
//   0x140 TG_CFG     RW test generator [15:0] frame bytes (reset 60) [31:16] gap cycles (reset 3)
//   0x144 FIFO_MAX   RO highest data FIFO level since reset (words of 8 bytes; size 32768)
//   0x150 RX_FRAMES  RO frames from the MAC (or generator), all     \
//   0x158 RX_BYTES   RO bytes of those                               |
//   0x160 CAP_FRAMES RO frames accepted into the buffers             | 64-bit: read lo
//   0x168 DROP_FRAMES RO frames dropped, buffers full (while enabled) | (latches hi),
//   0x170 BAD_FRAMES RO FCS / framing errors                         | then hi.
//   0x178 RECORDS    RO records handed to the DMA writer             | rx-side counters
//   0x180 TLPS       RO memory write TLPs sent                       | update every 105 us
//   0x188 STALLS     RO writer decisions blocked by a full host ring  |
//   0x190 TG_SEQ     RO frames generated by the test generator      /
`default_nettype none
module cap_top (
  input  wire         clk,          // PCIe user clock
  input  wire         rst,          // por | user_reset
  input  wire         rx_clk,
  input  wire         rx_rst,       // SFP A RX PCS reset
  input  wire [63:0]  xgmii_rxd,
  input  wire [7:0]   xgmii_rxc,
  input  wire         ts_clk,
  input  wire         sfp_a_lock,   // async

  // register bus (clk): req strobe, read data the cycle after
  input  wire         req,
  input  wire         we,
  input  wire [11:2]  addr,
  input  wire [31:0]  wdata,
  output reg  [31:0]  rdata,

  input  wire [15:0]  requester_id,
  input  wire         bus_master_en,
  input  wire [2:0]   cfg_mps,

  output wire [63:0]  tx_tdata,
  output wire [7:0]   tx_tkeep,
  output wire         tx_tlast,
  output wire         tx_tvalid,
  input  wire         tx_tready
);
  localparam integer DAW = 15, MAW = 12;

  // ---------------- registers ----------------
  reg        r_enable = 1'b0, r_reset = 1'b0, r_keep_bad = 1'b0, r_keep_fcs = 1'b0, r_tg = 1'b0;
  reg [14:0] r_snap = 15'd9600;
  reg [4:0]  r_blk_shift = 5'd21;
  reg [10:0] r_nblocks = 11'd1;
  reg [9:0]  r_tbl_idx = 0;
  reg [31:0] r_tbl_lo = 0;
  reg [15:0] r_timeout = 16'd250;
  reg [63:0] r_stat_addr = 0;
  reg [31:0] r_stat_thr = 32'd65536;
  reg [31:0] r_tail = 0;
  reg [31:0] r_tg_cfg = {16'd3, 16'd60};
  reg        tbl_we = 1'b0;
  reg [63:0] tbl_wdata = 0;
  reg [9:0]  tbl_waddr = 0;
  reg [31:0] hi_hold = 0;

  // capture reset, registered (drives asynchronous resets)
  reg cap_rst = 1'b1;
  always @(posedge clk) cap_rst <= rst | r_reset;

  // ---------------- timestamp: ts_clk counter, Gray to clk and rx_clk ----------------
  reg [63:0] ts_bin = 0, ts_gray = 0;
  always @(posedge ts_clk) begin
    ts_bin  <= ts_bin + 1'b1;
    ts_gray <= ts_bin ^ (ts_bin >> 1);
  end
  function [63:0] g2b(input [63:0] g);
    integer k;
    for (k = 0; k < 64; k = k + 1) g2b[k] = ^(g >> k);
  endfunction
  (* ASYNC_REG = "TRUE" *) reg [63:0] tsu_s1 = 0, tsu_s2 = 0;
  (* ASYNC_REG = "TRUE" *) reg [63:0] tsr_s1 = 0, tsr_s2 = 0;
  reg [63:0] ts_u = 0, ts_r = 0;
  always @(posedge clk)    begin tsu_s1 <= ts_gray; tsu_s2 <= tsu_s1; ts_u <= g2b(tsu_s2); end
  always @(posedge rx_clk) begin tsr_s1 <= ts_gray; tsr_s2 <= tsr_s1; ts_r <= g2b(tsr_s2); end

  // ---------------- rx_clk domain ----------------
  (* ASYNC_REG = "TRUE" *) reg [2:0] rrst_s = 3'b111;
  always @(posedge rx_clk or posedge cap_rst)
    if (cap_rst) rrst_s <= 3'b111; else rrst_s <= {rrst_s[1:0], 1'b0};
  wire cap_rst_rx = rrst_s[2];

  (* ASYNC_REG = "TRUE" *) reg [4:0]  cfg_s1 = 0, cfg_s2 = 0;
  (* ASYNC_REG = "TRUE" *) reg [11:0] snap_s1 = 0, snap_s2 = 0;
  (* ASYNC_REG = "TRUE" *) reg [31:0] tg_s1 = 0, tg_s2 = 0;
  always @(posedge rx_clk) begin
    cfg_s1  <= {r_tg, r_keep_fcs, r_keep_bad, r_enable & bus_master_en, 1'b0};
    cfg_s2  <= cfg_s1;
    snap_s1 <= r_snap[14:3];  snap_s2 <= snap_s1;
    tg_s1   <= r_tg_cfg;      tg_s2   <= tg_s1;
  end
  wire rx_enable = cfg_s2[1], rx_keep_bad = cfg_s2[2], rx_keep_fcs = cfg_s2[3], rx_tg = cfg_s2[4];

  // MAC receiver (verilog-ethernet, patched for keep_fcs)
  wire [63:0] mac_tdata;  wire [7:0] mac_tkeep;  wire mac_tvalid, mac_tlast, mac_tuser;
  axis_xgmii_rx_64 #(.PTP_TS_ENABLE(0)) mac_rx (
    .clk(rx_clk), .rst(rx_rst),
    .xgmii_rxd(xgmii_rxd), .xgmii_rxc(xgmii_rxc),
    .m_axis_tdata(mac_tdata), .m_axis_tkeep(mac_tkeep), .m_axis_tvalid(mac_tvalid),
    .m_axis_tlast(mac_tlast), .m_axis_tuser(mac_tuser),
    .ptp_ts(96'd0), .cfg_rx_enable(1'b1), .cfg_keep_fcs(rx_keep_fcs),
    .start_packet(), .error_bad_frame(), .error_bad_fcs()
  );

  wire [63:0] tg_tdata;  wire [7:0] tg_tkeep;  wire tg_tvalid, tg_tlast;  wire [63:0] tg_seq;
  cap_testgen tg (
    .clk(rx_clk), .rst(cap_rst_rx), .enable(rx_tg & rx_enable),
    .cfg_len(tg_s2[15:0]), .cfg_gap(tg_s2[31:16]),
    .m_tdata(tg_tdata), .m_tkeep(tg_tkeep), .m_tvalid(tg_tvalid), .m_tlast(tg_tlast), .seq(tg_seq)
  );

  // input select: switch only between frames of the MAC stream
  reg use_tg = 1'b0, mac_in_frame = 1'b0;
  always @(posedge rx_clk) begin
    if (mac_tvalid) mac_in_frame <= !mac_tlast;
    if (rx_rst) mac_in_frame <= 1'b0;
    if (!mac_in_frame && !mac_tvalid && !tg_tvalid) use_tg <= rx_tg;
  end
  wire [63:0] in_tdata  = use_tg ? tg_tdata  : mac_tdata;
  wire [7:0]  in_tkeep  = use_tg ? tg_tkeep  : mac_tkeep;
  wire        in_tvalid = use_tg ? tg_tvalid : mac_tvalid;
  wire        in_tlast  = use_tg ? tg_tlast  : mac_tlast;
  wire        in_tuser  = use_tg ? 1'b0      : mac_tuser;

  wire         d_we;  wire [63:0] d_wdata;  wire [DAW:0] d_free;
  wire         m_we;  wire [127:0] m_wdata; wire [MAW:0] m_free;
  wire [63:0]  c_rx_frames, c_rx_bytes, c_cap_frames, c_drop_frames, c_bad_frames;
  wire [DAW:0] c_dmax;

  cap_ingress #(.DAW(DAW), .MAW(MAW)) ingress (
    .clk(rx_clk), .rst(cap_rst_rx), .mac_rst(rx_rst & ~use_tg),
    .s_tdata(in_tdata), .s_tkeep(in_tkeep), .s_tvalid(in_tvalid), .s_tlast(in_tlast), .s_tuser(in_tuser),
    .ts(ts_r), .cfg_enable(rx_enable), .cfg_snap_words(snap_s2), .cfg_keep_bad(rx_keep_bad),
    .cfg_keep_fcs(rx_keep_fcs),
    .d_we(d_we), .d_data(d_wdata), .d_free(d_free),
    .m_we(m_we), .m_data(m_wdata), .m_free(m_free),
    .c_rx_frames(c_rx_frames), .c_rx_bytes(c_rx_bytes), .c_cap_frames(c_cap_frames),
    .c_drop_frames(c_drop_frames), .c_bad_frames(c_bad_frames), .c_dfifo_max_used(c_dmax)
  );

  // counter snapshots every 2^14 rx_clk cycles (105 us)
  reg [13:0]  snap_cnt = 0;
  reg         snap_tgl = 1'b0;
  reg [63:0]  sh_rxf = 0, sh_rxb = 0, sh_cap = 0, sh_drop = 0, sh_bad = 0, sh_tg = 0;
  reg [DAW:0] sh_dmax = 0;
  always @(posedge rx_clk) begin
    snap_cnt <= snap_cnt + 1'b1;
    if (snap_cnt == 0) begin
      sh_rxf <= c_rx_frames;  sh_rxb <= c_rx_bytes;  sh_cap <= c_cap_frames;
      sh_drop <= c_drop_frames;  sh_bad <= c_bad_frames;  sh_tg <= tg_seq;  sh_dmax <= c_dmax;
    end
    if (snap_cnt == 14'd8) snap_tgl <= ~snap_tgl;
  end

  // ---------------- FIFOs ----------------
  wire [63:0]  d_rdata;  wire d_rvalid, d_rpop;
  wire [127:0] m_rdata;  wire m_rvalid, m_rpop;
  afifo #(.W(64), .AW(DAW)) dfifo (
    .wclk(rx_clk), .wrst(cap_rst_rx), .wr_en(d_we), .wr_data(d_wdata), .wr_free(d_free),
    .rclk(clk), .rrst(cap_rst), .rd_data(d_rdata), .rd_valid(d_rvalid), .rd_pop(d_rpop), .rd_avail()
  );
  afifo #(.W(128), .AW(MAW)) mfifo (
    .wclk(rx_clk), .wrst(cap_rst_rx), .wr_en(m_we), .wr_data(m_wdata), .wr_free(m_free),
    .rclk(clk), .rrst(cap_rst), .rd_data(m_rdata), .rd_valid(m_rvalid), .rd_pop(m_rpop), .rd_avail()
  );

  // ---------------- DMA ----------------
  wire [63:0] head, c_tlps, c_stall, c_records;
  wire [9:0]  pf_level;
  // The DMA keeps running after CTRL.enable drops (drains what is buffered) until reset.
  reg         r_armed = 1'b0;
  always @(posedge clk) if (cap_rst) r_armed <= 1'b0; else if (r_enable) r_armed <= 1'b1;
  wire        run = r_armed & bus_master_en;
  cap_dma dma (
    .clk(clk), .rst(cap_rst),
    .m_data(m_rdata), .m_valid(m_rvalid), .m_pop(m_rpop),
    .d_data(d_rdata), .d_valid(d_rvalid), .d_pop(d_rpop),
    .cfg_run(run), .cfg_mps(cfg_mps), .cfg_blk_shift(r_blk_shift), .cfg_nblocks(r_nblocks),
    .cfg_tail(r_tail), .cfg_stat_addr(r_stat_addr), .cfg_stat_thresh(r_stat_thr),
    .cfg_timeout(r_timeout), .requester_id(requester_id),
    .tbl_we(tbl_we), .tbl_waddr(tbl_waddr), .tbl_wdata(tbl_wdata),
    .tx_tdata(tx_tdata), .tx_tkeep(tx_tkeep), .tx_tlast(tx_tlast), .tx_tvalid(tx_tvalid), .tx_tready(tx_tready),
    .head(head), .c_tlps(c_tlps), .c_stall(c_stall), .c_records(c_records), .pf_level(pf_level)
  );

  // ---------------- clk domain: counter copies, register access ----------------
  (* ASYNC_REG = "TRUE" *) reg [2:0] snap_s = 0;
  (* ASYNC_REG = "TRUE" *) reg [1:0] lock_s = 0;
  reg [63:0]  u_rxf = 0, u_rxb = 0, u_cap = 0, u_drop = 0, u_bad = 0, u_tg = 0;
  reg [DAW:0] u_dmax = 0;
  always @(posedge clk) begin
    snap_s <= {snap_s[1:0], snap_tgl};
    lock_s <= {lock_s[0], sfp_a_lock};
    if (snap_s[2] != snap_s[1]) begin
      u_rxf <= sh_rxf;  u_rxb <= sh_rxb;  u_cap <= sh_cap;  u_drop <= sh_drop;
      u_bad <= sh_bad;  u_tg <= sh_tg;  u_dmax <= sh_dmax;
    end
  end

  wire wr = req && we && addr[11:8] == 4'h1;
  wire rd = req && !we && addr[11:8] == 4'h1;
  reg [63:0] sel64;
  always @* begin
    case (addr[7:3])
      5'h06: sel64 = head;
      5'h07: sel64 = ts_u;
      5'h0A: sel64 = u_rxf;
      5'h0B: sel64 = u_rxb;
      5'h0C: sel64 = u_cap;
      5'h0D: sel64 = u_drop;
      5'h0E: sel64 = u_bad;
      5'h0F: sel64 = c_records;
      5'h10: sel64 = c_tlps;
      5'h11: sel64 = c_stall;
      5'h12: sel64 = u_tg;
      default: sel64 = 64'd0;
    endcase
  end

  always @(posedge clk) begin
    tbl_we <= 1'b0;
    if (req) begin
      if (addr[7:2] >= 6'h0C && addr[7:2] != 6'h10 && addr[7:2] != 6'h11 && !addr[2]) begin
        rdata <= sel64[31:0];
        if (rd) hi_hold <= sel64[63:32];
      end else case (addr[7:2])
        6'h00: rdata <= {27'd0, r_tg, r_keep_fcs, r_keep_bad, r_reset, r_enable};
        6'h01: rdata <= {6'd0, pf_level, 10'd0, lock_s[1], cfg_mps, run, bus_master_en};
        6'h02: rdata <= {17'd0, r_snap};
        6'h03: rdata <= {5'd0, r_nblocks, 11'd0, r_blk_shift};
        6'h04: rdata <= {22'd0, r_tbl_idx};
        6'h05: rdata <= r_tbl_lo;
        6'h07: rdata <= {16'd0, r_timeout};
        6'h08: rdata <= r_stat_addr[31:0];
        6'h09: rdata <= r_stat_addr[63:32];
        6'h0A: rdata <= r_stat_thr;
        6'h0B: rdata <= r_tail;
        6'h10: rdata <= r_tg_cfg;
        6'h11: rdata <= {16'd0, u_dmax};
        default: rdata <= (addr[7:2] >= 6'h0C) ? hi_hold : 32'd0;
      endcase
    end
    if (wr) case (addr[7:2])
      6'h00: begin
        r_enable <= wdata[0];  r_reset <= wdata[1];  r_keep_bad <= wdata[2];
        r_keep_fcs <= wdata[3];  r_tg <= wdata[4];
      end
      6'h02: r_snap <= (wdata > 32'd16384) ? 15'd16384 :
                       (wdata < 32'd64) ? 15'd64 : {wdata[14:3], 3'b000};
      6'h03: begin
        r_blk_shift <= (wdata[4:0] < 5'd12) ? 5'd12 : (wdata[4:0] > 5'd30 ? 5'd30 : wdata[4:0]);
        r_nblocks   <= (wdata[26:16] == 0) ? 11'd1 : (wdata[26:16] > 11'd1024 ? 11'd1024 : wdata[26:16]);
      end
      6'h04: r_tbl_idx <= wdata[9:0];
      6'h05: r_tbl_lo  <= wdata;
      6'h06: begin
        tbl_we <= 1'b1;  tbl_waddr <= r_tbl_idx;  tbl_wdata <= {wdata, r_tbl_lo};
        r_tbl_idx <= r_tbl_idx + 1'b1;
      end
      6'h07: r_timeout <= (wdata[15:0] == 0) ? 16'd1 : wdata[15:0];
      6'h08: r_stat_addr[31:0]  <= {wdata[31:3], 3'b000};
      6'h09: r_stat_addr[63:32] <= wdata;
      6'h0A: r_stat_thr <= wdata;
      6'h0B: r_tail <= wdata;
      6'h10: r_tg_cfg <= wdata;
      default: ;
    endcase
    if (rst) begin
      r_enable <= 1'b0;  r_reset <= 1'b0;
    end
  end
endmodule
`default_nettype wire
